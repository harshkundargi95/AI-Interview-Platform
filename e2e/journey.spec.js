const { test, expect } = require('@playwright/test')
test('signed test identity → configure → saved interview → feedback → history → delete', async ({ page }) => {
  await page.goto('/setup')
  await expect(page.getByRole('heading', { name: 'Sign in to practice' })).toBeVisible()
  await page.getByRole('button', { name: 'Sign in with test identity' }).click()
  await page.getByLabel('Job role', { exact: true }).selectOption('backend')
  await page.getByLabel('Interview type', { exact: true }).selectOption('technical')
  await page.getByLabel('Question count', { exact: true }).selectOption('3')
  await page.getByRole('button', { name: 'Start interview →' }).click()
  for (let i = 1; i <= 3; i++) {
    await expect(page.getByText(`Question ${i} of 3`, { exact: true })).toBeVisible()
    await page.getByRole('textbox', { name: 'Your answer', exact: true }).fill(`Synthetic answer ${i}: validate inputs, check authorization and test errors.`)
    if (i < 3) await page.getByRole('button', { name: 'Next question →' }).click()
  }
  await page.getByRole('button', { name: 'Complete interview', exact: true }).click()
  await page.getByRole('button', { name: 'Generate feedback', exact: true }).click()
  await expect(page.getByText('Mock report · not an assessment', { exact: true })).toBeVisible()
  await expect(page.getByText('<img src=x onerror="window.injected=true"> Plain text safety probe.', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.injected)).toBeUndefined()
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Review answers', exact: true }).click()
  await expect(page.getByText('Mock report · not an assessment', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await page.getByRole('button', { name: 'Delete interview', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click()
  await expect(page.getByText('Your first chapter is still ahead.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.goto('/history')
  await expect(page.getByRole('heading', { name: 'Sign in to practice' })).toBeVisible()
})
